// dbTx wraps a database transaction for migrations.
type dbTx struct {
	exec func(query string, args ...any) error
}

// isDuplicateColumnErr 判断"列已存在"错误：兼容 SQLite（duplicate column）
// 与 PostgreSQL（already exists / SQLSTATE 42703）文案。
func isDuplicateColumnErr(err error) bool {
	if err == nil {
		return false
	}
	msg := err.Error()
	return strings.Contains(msg, "duplicate column") ||
		strings.Contains(msg, "already exists") ||
		strings.Contains(msg, "42703")
}

// RunMigrations applies any pending schema migrations.
func RunMigrations() error {
	if db == nil {
		return nil
	}

	// Ensure version tracking table
	db.Exec(`CREATE TABLE IF NOT EXISTS schema_version (version BIGINT PRIMARY KEY)`)

	var currentVersion int
	row := db.QueryRow("SELECT COALESCE(MAX(version), 0) FROM schema_version")
	if err := row.Scan(&currentVersion); err != nil {
		currentVersion = 0
	}

	for v := currentVersion + 1; v <= currentSchemaVersion; v++ {
		migrateFn, ok := migrations[v]
		if !ok {
			continue
		}

		tx, err := db.Begin()
		if err != nil {
			return err
		}

		wrapper := &dbTx{
			exec: func(query string, args ...any) error {
				_, err := tx.Exec(query, args...)
				// 列已存在容错（PG 下重复 ADD COLUMN 不会中止事务，此处再兜底）。
				if isDuplicateColumnErr(err) {
					return nil
				}
				return err
			},
		}

		if err := migrateFn(wrapper); err != nil {
			tx.Rollback()
			return err
		}

		if _, err := tx.Exec("INSERT INTO schema_version (version) VALUES ($1) ON CONFLICT (version) DO UPDATE SET version = excluded.version", v); err != nil {
			tx.Rollback()
			return err
		}

		if err := tx.Commit(); err != nil {
			return err
		}
	}

	// Go 版本迁移完成后应用纯 SQL 迁移（migrations/sql/*.sql）。
	return RunSQLMigrations()
}

