-- 0061: D1 复式账本流水 ledger_entries（append-only，幂等键去重）
-- 日期: 2026-11-26
--
-- 背景: 此前余额是账户上的快照值，成交/手续费/平仓后的变动没有流水可追溯。
-- ledger_entries 记录每一笔资金变动：方向(debit/credit)、金额、过账后余额快照、
-- 业务类型/单号、幂等键。余额由流水重算派生（见 D2），快照仅做校验对账。
--
-- 方向约定:
--   debit  冻结/支出/扣费/划出（余额减少）
--   credit 释放/收入/入账/划入（余额增加）
--   amount 一律为非负绝对值，方向由 direction 表达。
--
-- 注意: 语句内不要出现分号(字符串/注释里也不行)——迁移按分号切分执行。

CREATE TABLE IF NOT EXISTS ledger_entries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL DEFAULT 0,
    account TEXT NOT NULL DEFAULT 'default',
    asset TEXT NOT NULL,
    direction TEXT NOT NULL,
    amount DOUBLE PRECISION NOT NULL,
    balance_after DOUBLE PRECISION NOT NULL DEFAULT 0,
    biz_type TEXT NOT NULL,
    biz_id TEXT NOT NULL DEFAULT '',
    idempotency_key TEXT NOT NULL,
    detail TEXT DEFAULT '',
    created_at BIGINT NOT NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_ledger_idem ON ledger_entries(idempotency_key);
CREATE INDEX IF NOT EXISTS idx_ledger_user_asset ON ledger_entries(user_id, account, asset, created_at);
CREATE INDEX IF NOT EXISTS idx_ledger_biz ON ledger_entries(biz_type, biz_id);
